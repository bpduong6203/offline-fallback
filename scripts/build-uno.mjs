import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));

export async function buildUno() {
  const seen = new Set();
  const modules = [];

  async function visit(name) {
    if (seen.has(name)) return;
    seen.add(name);

    let code = (await readFile(path.join(root, 'uno', name), 'utf8')).replace(/^\uFEFF/, '');
    const pattern = /import\s+\{([^}]+)\}\s+from\s+'\.\/([^']+)';/g;

    for (const match of [...code.matchAll(pattern)]) {
      await visit(match[2]);
    }

    const exports = [...code.matchAll(/export (?:const|function|class) ([\w$]+)/g)].map(m => m[1]);
    code = code
      .replace(pattern, (_, names, file) => `const {${names}} = modules[${JSON.stringify(file)}];`)
      .replace(/export /g, '');

    modules.push(`modules[${JSON.stringify(name)}] = (() => {\n${code}\nreturn {${exports.join(',')}};\n})();`);
  }

  await visit('main.js');

  const template = await readFile(path.join(root, 'uno/index.html'), 'utf8');
  const css = (await readFile(path.join(root, 'uno/style.css'), 'utf8')).replace(/^\uFEFF/, '');

  const html = template
    .replace('/* STYLE */', () => css)
    .replace('/* SCRIPT */', () => `(() => {\n'use strict';\nconst modules = {};\n${modules.join('\n')}\n})();`);

  await mkdir(path.join(root, 'dist/uno'), { recursive: true });
  await writeFile(path.join(root, 'dist/uno/index.html'), html);
  await writeFile(
    path.join(root, 'src/page/games/uno.generated.js'),
    `// Generated by npm run build. Do not edit.\nexport default ${JSON.stringify(html)};\n`
  );

  console.log(`Built UNO Arena (${Buffer.byteLength(html)} bytes)`);
  return html;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await buildUno();
}
