import {readFile,mkdir,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {buildStickman} from './build-stickman.mjs';
import {buildTienLen} from './build-tienlen.mjs';
import {buildUno} from './build-uno.mjs';
import {buildMonopoly} from './build-monopoly.mjs';
const root=fileURLToPath(new URL('../',import.meta.url));
export async function build(){
  const seen=new Set(),modules=[];
  async function visit(name){
    if(seen.has(name))return;seen.add(name);
    let code=await readFile(path.join(root,'bomb-arena',name),'utf8');
    const imports=[...code.matchAll(/import\s+\{([^}]+)\}\s+from\s+'\.\/([^']+)';/g)];
    for(const match of imports)await visit(match[2]);
    const exports=[...code.matchAll(/export (?:const|function|class) (\w+)/g)].map(m=>m[1]);
    code=code.replace(/import\s+\{([^}]+)\}\s+from\s+'\.\/([^']+)';/g,(_,names,file)=>`const {${names}} = modules[${JSON.stringify(file)}];`).replace(/export /g,'');
    modules.push(`modules[${JSON.stringify(name)}] = (()=>{\n${code}\nreturn {${exports.join(',')}};\n})();`);
  }
  await visit('main.js');
  const script=`const modules = {};\n${modules.join('\n')}`;
  const template=await readFile(path.join(root,'bomb-arena/index.html'),'utf8');
  // An inline stylesheet cannot contain a UTF-8 BOM before its first selector.
  // PowerShell-written files may include one; strip it before embedding in HTML.
  const css=(await readFile(path.join(root,'bomb-arena/style.css'),'utf8')).replace(/^\uFEFF/,'');
  const html=template.replace('/* STYLE */',()=>css).replace('/* SCRIPT */',()=>script);
  await mkdir(path.join(root,'dist'),{recursive:true});
  await writeFile(path.join(root,'dist/index.html'),html);
  // ESM text export lets Wrangler use the same self-contained build without asset bindings.
  await writeFile(path.join(root,'src/page/games/bomb-arena.generated.js'),`// Generated by npm run build. Do not edit.\nexport default ${JSON.stringify(html)};\n`);
  console.log(`Built Bomb Arena (${Buffer.byteLength(html)} bytes)`);
  await buildStickman();
  await buildTienLen();
  await buildUno();
  await buildMonopoly();
  return html;
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))await build();
