import {build} from 'esbuild';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
export async function buildXiDach(){
  const root=new URL('../',import.meta.url);
  const bundled=await build({entryPoints:[new URL('xi-dach/client.js',root).pathname.replace(/^\/([A-Za-z]:)/,'$1')],bundle:true,write:false,format:'iife',target:'es2022',minify:false});
  const template=await readFile(new URL('xi-dach/index.html',root),'utf8'),css=await readFile(new URL('xi-dach/style.css',root),'utf8');
  const html=template.replace('/* STYLE */',()=>css).replace('/* SCRIPT */',()=>bundled.outputFiles[0].text.replace(/<\/script/gi,'<\\/script'));
  await mkdir(new URL('dist/xi-dach/',root),{recursive:true});
  await writeFile(new URL('dist/xi-dach/index.html',root),html);
  await writeFile(new URL('src/page/games/xi-dach.generated.js',root),`// Generated by npm run build. Do not edit.\nexport default ${JSON.stringify(html)};\n`);
  console.log(`Built Xì Dách (${Buffer.byteLength(html)} bytes)`);return html;
}
